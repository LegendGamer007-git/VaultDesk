/**
 * Helper to get all symptom areas for a given component
 */
export function getSymptomAreasForComponent(component: PamComponent): SymptomAreaDetail[] {
  return COMPONENT_SYMPTOM_PROFILES[component]?.symptomAreas || [];
}

/**
 * Helper to get all symptom areas across all components
 */
export function getAllSymptomAreas(): SymptomAreaDetail[] {
  const all: SymptomAreaDetail[] = [];
  (Object.keys(COMPONENT_SYMPTOM_PROFILES) as PamComponent[]).forEach((comp) => {
    all.push(...COMPONENT_SYMPTOM_PROFILES[comp].symptomAreas);
  });
  return all;
}

/**
 * Helper to find a symptom area by ID
 */
export function getSymptomAreaById(id: string): SymptomAreaDetail | undefined {
  return getAllSymptomAreas().find((sa) => sa.id === id);
}
